import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdir, readFile } from 'node:fs/promises'

test('the full page renders with local images, no runtime errors, and no horizontal overflow', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Your idea.')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Built the right way.')
  await expect(page.getByRole('button', { name: 'All projects', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.project-card')).toHaveCount(2)
  await expect(page.locator('.services-grid > a')).toHaveCount(6)
  await page.locator('.site-footer').scrollIntoViewIfNeeded()
  await page.evaluate(async () => { await document.fonts.ready; await Promise.all(Array.from(document.images).map(img => { img.loading = 'eager'; return img.decode() })) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await page.evaluate(() => window.scrollTo(0, 0))
  await mkdir('.preview', { recursive: true })
  await page.screenshot({ path: `.preview/${testInfo.project.name}.png`, fullPage: true })
})

