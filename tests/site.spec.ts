test('inquiries validate fields, create a real email draft, and download the brief', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Discuss your project', exact: true }).click()
  await page.getByRole('button', { name: 'Prepare my inquiry' }).click()
  expect(await page.getByRole('textbox', { name: 'Your name' }).evaluate((input: HTMLInputElement) => input.validity.valid)).toBe(false)
  await page.getByRole('textbox', { name: 'Your name' }).fill('Taylor Lane')
  await page.getByRole('textbox', { name: 'Email address' }).fill('taylor@example.com')
  await page.getByRole('textbox', { name: 'Business or website' }).fill('Taylor Digital')
  await page.getByLabel('Budget in USD').selectOption('$5,000–$10,000')
  await page.getByLabel('Ideal timing').selectOption('In 1–3 months')
  await page.getByRole('textbox', { name: 'Tell us a little about your project' }).fill('We need a customer-facing SaaS platform and a connected mobile experience.')
  await page.getByRole('button', { name: 'Prepare my inquiry' }).click()
  await expect(page.getByText('Your next chapter is ready.')).toBeVisible()
  const href = await page.getByRole('link', { name: 'Open email draft' }).getAttribute('href')
  expect(href).toContain('mailto:abhilashpal128@gmail.com?')
  const query = new URLSearchParams(href!.split('?')[1])
  expect(query.get('body')).toContain('Taylor Digital')
  expect(query.get('body')).toContain('$5,000–$10,000')
  expect(query.get('body')).toContain('taylor@example.com')
  await expect(page.getByText(/Nothing has been sent yet/)).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download brief' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('orris-and-code-project-brief.txt')
  expect(await readFile((await download.path())!, 'utf8')).toBe(query.get('body'))
})

